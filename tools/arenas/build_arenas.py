def sc(v): return [round(x * K) for x in v]

def foot(r):
    """見下ろしの 絵なので、ぶつかるのは 足もとだけ：上の 35% と 左右 5% を けずる"""
    x0, y0, x1, y1 = r; w, h = x1 - x0, y1 - y0
    return [x0 + w * .05, y0 + h * .35, x1 - w * .05, y1]

def main():
    out = {}
    for name, a in ARENAS.items():
        im = Image.open(os.path.join(HERE, 'src', name + '.webp')).convert('RGB')
        W, H = round(im.width * K), round(im.height * K)
        im = im.resize((W, H), Image.LANCZOS)
        buf = io.BytesIO(); im.save(buf, 'WEBP', quality=82, method=6)
        out[name] = {'name': a['name'], 'W': W, 'H': H, 'floor': sc(a['floor']), 'trainers': [sc(t) for t in a['trainers']],
                     'solid': [sc(r) for r in a['solid'][:2]] + [sc(foot(r)) for r in a['solid'][2:]], 'low': [sc(r) for r in a['low']],
                     'img': 'data:image/webp;base64,' + base64.b64encode(buf.getvalue()).decode()}
        print(name, W, H, len(buf.getvalue()) // 1024, 'KB')
    js = BEGIN + '\n// 大会の 闘技場の 絵と 当たり判定（solid＝通れない・弾も 止まる、low＝通れないが 弾は 飛ぶ）。座標は ゲームの 世界座標\n'
    js += 'const ARENAS = %s;\n' % json.dumps(out, ensure_ascii=False, separators=(',', ':'))
    js += 'for (const k in ARENAS) { const im = new Image(); im.src = ARENAS[k].img; ARENAS[k].image = im; }\n' + END
    src = open(GAME).read()
    if BEGIN in src: i = src.index(BEGIN); j = src.index(END) + len(END); src = src[:i] + js + src[j:]
    else: k = src.index("const FIELDS = "); src = src[:k] + js + '\n' + src[k:]
    open(GAME, 'w').write(src)

if __name__ == '__main__':
    main()
